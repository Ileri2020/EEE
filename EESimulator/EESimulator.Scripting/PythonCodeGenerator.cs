/// <summary>
/// Generates idiomatic Python code from commands and circuit hierarchy.
/// Supports all registered component types and maps each to the appropriate
/// high-level PythonApi call signature so that generated scripts are round-trippable.
/// </summary>
public class PythonCodeGenerator
{
    /// <summary>
    /// Generates a complete Python script reflecting the current state of <paramref name="circuit"/>.
    /// Called after undo operations, project loads, and new-circuit operations so the script
    /// viewport is never left blank or stale.
    /// </summary>
    public static string GenerateFullScript(CircuitNode circuit)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Automatically generated by EESimulator Python Scripting Interface");
        sb.AppendLine("import eesim");
        sb.AppendLine();
        sb.AppendLine($"circuit = eesim.new_circuit({JsonSerializer.Serialize(circuit.Title)})");
        sb.AppendLine();

        // ── Components ────────────────────────────────────────────────────────
        sb.AppendLine("# Components");
        foreach (var comp in circuit.Components)
        {
            var varName = SanitizePythonName(comp.Name);
            sb.AppendLine(BuildExecutableAddStatement(varName, comp));
            foreach (string statement in BuildConfigurationStatements(comp))
                sb.AppendLine(statement);
        }

        // ── Connections ───────────────────────────────────────────────────────
        sb.AppendLine();
        sb.AppendLine("# Connections");
        var allComponents = circuit.FindChildren<ComponentNode>().ToList();
        foreach (var conn in circuit.Connections)
        {
            var fromComp = allComponents.FirstOrDefault(c => c.Id == conn.FromComponentId);
            var toComp = allComponents.FirstOrDefault(c => c.Id == conn.ToComponentId);

            if (fromComp != null && toComp != null)
            {
                sb.AppendLine(
                    $"eesim.connect({JsonSerializer.Serialize(fromComp.Name)}, " +
                    $"{JsonSerializer.Serialize(conn.FromPin)}, {JsonSerializer.Serialize(toComp.Name)}, " +
                    $"{JsonSerializer.Serialize(conn.ToPin)}, {FormatNumber(conn.Resistance)})");
            }
        }

        return sb.ToString();
    }

    private static string BuildExecutableAddStatement(string variableName, ComponentNode component)
    {
        string typeId = ComponentRegistry.GetAllDefinitions()
            .FirstOrDefault(definition => definition.NodeType == component.GetType())
            ?.StableTypeId ?? component.ComponentType;
        string name = JsonSerializer.Serialize(component.Name);
        string type = JsonSerializer.Serialize(typeId);

        if (component.LogicalRow is int row && component.LogicalColumn is int column)
            return $"{variableName} = circuit.add_component({type}, name={name}, row={row}, col={column})";

        return $"{variableName} = circuit.add_component({type}, name={name}, " +
            $"position=({FormatNumber(component.X)}, {FormatNumber(component.Y)}))";
    }

    private static IEnumerable<string> BuildConfigurationStatements(ComponentNode component)
    {
        string name = JsonSerializer.Serialize(component.Name);
        var emittedProperties = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var excludedProperties = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "Id", "Parent", "Children", "Pins", "Name", "Reference", "Description",
            "Position", "X", "Y", "Rotation", "ScaleX", "ScaleY", "CustomProperties",
            "ElectricalParameters", "WaveformTime", "WaveformVoltage", "WaveformCurrent",
            "LivePinVoltages", "WaveformNodeVoltages", "WaveformPinCurrents",
            "LogicalRow", "LogicalColumn", "IsHigh", "IsOn"
        };

        if (!string.IsNullOrWhiteSpace(component.Description))
            yield return $"eesim.set_description({name}, {JsonSerializer.Serialize(component.Description)})";
        if (Math.Abs(component.Rotation) > 0.001)
            yield return $"eesim.rotate_component({name}, {FormatNumber(component.Rotation)})";
        if (Math.Abs(component.ScaleX - 1) > 0.001 || Math.Abs(component.ScaleY - 1) > 0.001)
            yield return $"eesim.stretch_component({name}, {FormatNumber(component.ScaleX)}, {FormatNumber(component.ScaleY)})";

        if (component is LogicInputComponent logicInput)
        {
            bool state = logicInput.State;
            if (!logicInput.CustomProperties.ContainsKey(nameof(LogicInputComponent.State)) &&
                !logicInput.ElectricalParameters.ContainsKey(nameof(LogicInputComponent.State)))
            {
                if (logicInput.CustomProperties.TryGetValue("IsHigh", out object? legacyState))
                    state = Convert.ToBoolean(legacyState, CultureInfo.InvariantCulture);
                else if (logicInput.ElectricalParameters.TryGetValue("IsHigh", out double legacyElectricalState))
                    state = legacyElectricalState > 0.5;
            }

            yield return $"eesim.set_logic({name}, {state.ToString().ToLowerInvariant()})";
            emittedProperties.Add(nameof(LogicInputComponent.State));
        }

        foreach (PropertyInfo property in component.GetType().GetProperties(BindingFlags.Instance | BindingFlags.Public))
        {
            if (!property.CanRead || property.SetMethod?.IsPublic != true ||
                property.GetIndexParameters().Length != 0 ||
                excludedProperties.Contains(property.Name) ||
                !IsSimpleProperty(property.PropertyType))
                continue;

            object? value;
            try
            {
                value = property.GetValue(component);
            }
            catch (TargetInvocationException exception)
            {
                throw new InvalidOperationException(
                    $"Could not read {property.Name} from {component.ComponentType} '{component.Name}'.",
                    exception);
            }

            if (!TryFormatPythonValue(value, out string formatted))
                continue;

            emittedProperties.Add(property.Name);
            yield return $"eesim.set_component_property({name}, {JsonSerializer.Serialize(property.Name)}, {formatted})";
        }

        foreach (var parameter in component.ElectricalParameters)
        {
            if (emittedProperties.Contains(parameter.Key) ||
                !TryFormatPythonValue(parameter.Value, out string formatted))
                continue;

            emittedProperties.Add(parameter.Key);
            yield return $"eesim.set_component_property({name}, {JsonSerializer.Serialize(parameter.Key)}, {formatted})";
        }

        foreach (var customProperty in component.CustomProperties)
        {
            if (emittedProperties.Contains(customProperty.Key) ||
                excludedProperties.Contains(customProperty.Key) ||
                customProperty.Key.StartsWith("_sim", StringComparison.Ordinal) ||
                customProperty.Key.StartsWith("_previous", StringComparison.Ordinal) ||
                customProperty.Key.StartsWith("_seen", StringComparison.Ordinal) ||
                !TryFormatPythonValue(customProperty.Value, out string formatted))
                continue;

            yield return $"eesim.set_custom_property({name}, {JsonSerializer.Serialize(customProperty.Key)}, {formatted})";
        }

        if (component is RAMComponent ram)
        {
            foreach (var word in ram.MemoryData)
                yield return $"eesim.set_memory_word({name}, {word.Key}, {word.Value})";
        }
        else if (component is ROMComponent rom)
        {
            foreach (var word in rom.MemoryData)
                yield return $"eesim.set_memory_word({name}, {word.Key}, {word.Value})";
        }
    }

    private static bool IsSimpleProperty(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        return type.IsPrimitive || type.IsEnum || type == typeof(string) || type == typeof(decimal);
    }

    private static bool TryFormatPythonValue(object? value, out string formatted)
    {
        switch (value)
        {
            case null:
                formatted = "None";
                return true;
            case bool boolean:
                formatted = boolean ? "True" : "False";
                return true;
            case string text:
                formatted = JsonSerializer.Serialize(text);
                return true;
            case Enum enumValue:
                formatted = JsonSerializer.Serialize(enumValue.ToString());
                return true;
            case IFormattable formattable:
                formatted = formattable.ToString(null, CultureInfo.InvariantCulture) ?? string.Empty;
                return true;
            default:
                formatted = string.Empty;
                return false;
        }
    }

    private static string FormatNumber(double value) => value.ToString("R", CultureInfo.InvariantCulture);

    /// <summary>
    /// Builds a Python assignment statement for the given component,
    /// mapping each type to the richest available PythonApi call.
    /// </summary>
    private static string BuildAddStatement(string varName, ComponentNode comp)
    {
        double x = comp.X, y = comp.Y;
        return comp switch
        {
            // ── Passives ─────────────────────────────────────────────────────
            ResistorComponent r =>
                $"{varName} = circuit.add_resistor(\"{comp.Name}\", position=({x}, {y}), resistance={r.Resistance}, tc1={r.TemperatureCoefficient1}, tc2={r.TemperatureCoefficient2}, power_rating={r.PowerRating}, tolerance={r.Tolerance})",

            CapacitorComponent c =>
                $"{varName} = circuit.add_capacitor(\"{comp.Name}\", position=({x}, {y}), capacitance={c.Capacitance}, ic={c.InitialCondition}, esr={c.EquivalentSeriesResistance}, tc1={c.TemperatureCoefficient1}, tc2={c.TemperatureCoefficient2})",

            InductorComponent l =>
                $"{varName} = circuit.add_inductor(\"{comp.Name}\", position=({x}, {y}), inductance={l.Inductance}, ic={l.InitialCondition}, dcr={l.DcResistance}, series_multiplier={l.SeriesMultiplier}, parallel_multiplier={l.ParallelMultiplier})",

            // ── Sources & Rails ───────────────────────────────────────────────
            VoltageSourceComponent v =>
                BuildVoltageSourceStatement(varName, comp.Name, x, y, v),

            CurrentSourceComponent i =>
                BuildCurrentSourceStatement(varName, comp.Name, x, y, i),

            PowerComponent pw =>
                $"{varName} = circuit.add_power(\"{comp.Name}\", position=({x}, {y}), voltage={pw.Voltage})",

            PullResistorComponent pr =>
                $"{varName} = circuit.add_pull_resistor(\"{comp.Name}\", position=({x}, {y}), mode=\"{pr.Mode}\", resistance={pr.Resistance}, rail_voltage={pr.RailVoltage})",

            GroundNode _ =>
                $"{varName} = circuit.add_ground(\"{comp.Name}\", position=({x}, {y}))",

            GroundComponent _ =>
                $"{varName} = circuit.add_ground(\"{comp.Name}\", position=({x}, {y}))",

            // ── Controlled Sources ───────────────────────────────────────────
            VCVSComponent vcvs =>
                $"{varName} = circuit.add_vcvs(\"{comp.Name}\", position=({x}, {y}), gain={vcvs.VoltageGain})",

            VCCSComponent vccs =>
                $"{varName} = circuit.add_vccs(\"{comp.Name}\", position=({x}, {y}), transconductance={vccs.Transconductance})",

            CCVSComponent ccvs =>
                $"{varName} = circuit.add_ccvs(\"{comp.Name}\", position=({x}, {y}), transresistance={ccvs.Transresistance}, controlling_source=\"{ccvs.ControllingSource}\")",

            CCCSComponent cccs =>
                $"{varName} = circuit.add_cccs(\"{comp.Name}\", position=({x}, {y}), gain={cccs.CurrentGain}, controlling_source=\"{cccs.ControllingSource}\")",

            // ── Switches & Delays ────────────────────────────────────────────
            VoltageSwitchComponent vsw =>
                $"{varName} = circuit.add_voltage_switch(\"{comp.Name}\", position=({x}, {y}), ron={vsw.ResistanceOn}, roff={vsw.ResistanceOff}, threshold={vsw.Threshold}, hysteresis={vsw.Hysteresis})",

            CurrentSwitchComponent csw =>
                $"{varName} = circuit.add_current_switch(\"{comp.Name}\", position=({x}, {y}), ron={csw.ResistanceOn}, roff={csw.ResistanceOff}, threshold={csw.Threshold}, hysteresis={csw.Hysteresis}, controlling_source=\"{csw.ControllingSource}\")",

            VoltageDelayComponent vd =>
                $"{varName} = circuit.add_voltage_delay(\"{comp.Name}\", position=({x}, {y}), delay={vd.Delay}, bandwidth={vd.Bandwidth})",

            MutualInductanceComponent mi =>
                $"{varName} = circuit.add_mutual_inductance(\"{comp.Name}\", position=({x}, {y}), inductor1=\"{mi.Inductor1}\", inductor2=\"{mi.Inductor2}\", coupling={mi.Coupling})",

            // ── Opto / Indicators ────────────────────────────────────────────
            BulbComponent bulb =>
                $"{varName} = circuit.add_bulb(\"{comp.Name}\", position=({x}, {y}), resistance={bulb.Resistance}, rated_voltage={bulb.RatedVoltage}, power_rating={bulb.PowerRating})",

            LEDComponent led =>
                $"{varName} = circuit.add_led(\"{comp.Name}\", position=({x}, {y}), color=\"{led.ColorName}\", vf={led.ForwardVoltage})",

            // ── Digital / Core Wiring ──────────────────────────────────────────
            ClockComponent clk =>
                $"{varName} = circuit.add_clock(\"{comp.Name}\", position=({x}, {y}), frequency={clk.Frequency}, duty_cycle={clk.DutyCycle}, high_voltage={clk.HighVoltage}, phase={clk.Phase})",

            PinComponent pin =>
                $"{varName} = circuit.add_pin(\"{comp.Name}\", position=({x}, {y}), direction=\"{pin.Direction}\", bit_width={pin.BitWidth}, value={pin.Value})",

            ConstantComponent cst =>
                $"{varName} = circuit.add_constant(\"{comp.Name}\", position=({x}, {y}), value={cst.Value}, voltage_high={cst.VoltageHigh}, voltage_low={cst.VoltageLow}, bit_width={cst.BitWidth})",

            LogicInputComponent lin =>
                $"{varName} = circuit.add_logic_input(\"{comp.Name}\", position=({x}, {y}), state={lin.State.ToString().ToLower()}, high_voltage={lin.HighVoltage}, low_voltage={lin.LowVoltage})",

            LogicOutputComponent lout =>
                $"{varName} = circuit.add_logic_output(\"{comp.Name}\", position=({x}, {y}), threshold={lout.Threshold}, high_value={lout.HighValue}, low_value={lout.LowValue})",

            DigitalTransistorComponent dtr =>
                $"{varName} = circuit.add_digital_transistor(\"{comp.Name}\", position=({x}, {y}), type=\"{dtr.TransistorType}\", ron={dtr.ResistanceOn}, roff={dtr.ResistanceOff}, threshold={dtr.Threshold}, gate_location=\"{dtr.GateLocation}\", bit_width={dtr.BitWidth})",

            TransmissionGateComponent tg =>
                $"{varName} = circuit.add_transmission_gate(\"{comp.Name}\", position=({x}, {y}), ron={tg.ResistanceOn}, roff={tg.ResistanceOff}, select_location=\"{tg.SelectLocation}\", bit_width={tg.BitWidth})",

            BitExtenderComponent be =>
                $"{varName} = circuit.add_bit_extender(\"{comp.Name}\", position=({x}, {y}), in_width={be.InputBitWidth}, out_width={be.OutputBitWidth}, type=\"{be.ExtensionType}\")",

            // ── Semiconductors ────────────────────────────────────────────────
            BJTComponent bjt =>
                $"{varName} = circuit.add_bjt(\"{comp.Name}\", position=({x}, {y}), polarity=\"{bjt.Polarity}\", bf={bjt.GainBeta}, br={bjt.ReverseGainBeta}, is_={bjt.SaturationCurrent:G3}, vaf={bjt.EarlyVoltage})",

            MOSFETComponent mos =>
                $"{varName} = circuit.add_mosfet(\"{comp.Name}\", position=({x}, {y}), channel=\"{mos.Channel}\", vto={mos.ThresholdVoltage}, kp={mos.Transconductance:G3}, w={mos.ChannelWidth:G3}, l={mos.ChannelLength:G3}, lambda_={mos.Lambda})",

            JFETComponent jfet =>
                $"{varName} = circuit.add_jfet(\"{comp.Name}\", position=({x}, {y}), channel=\"{jfet.Channel}\", vto={jfet.ThresholdVoltage}, beta={jfet.Transconductance:G3}, lambda_={jfet.Lambda}, dr={jfet.DrainResistance}, sr={jfet.SourceResistance})",

            DiodeComponent d =>
                $"{varName} = circuit.add_diode(\"{comp.Name}\", position=({x}, {y}), is_={d.SaturationCurrent:G3}, n={d.EmissionCoefficient}, rs={d.SeriesResistance:G3}, cj0={d.JunctionCapacitance:G3}, tt={d.TransitTime:G3}, bv={d.BreakdownVoltage}, ibv={d.BreakdownCurrent:G3})",

            OpAmpComponent op =>
                $"{varName} = circuit.add_opamp(\"{comp.Name}\", position=({x}, {y}), aol={op.OpenLoopGain:G3}, gbw={op.GainBandwidth:G3}, sr={op.SlewRate}, v_pos={op.SupplyPositive}, v_neg={op.SupplyNegative}, vos={op.InputOffsetVoltage:G3}, ib={op.InputBiasCurrent:G3}, cmrr={op.CMRR})",

            // ── Transmission Lines ───────────────────────────────────────────
            TransmissionLineComponent tl =>
                $"{varName} = circuit.add_transmission_line(\"{comp.Name}\", position=({x}, {y}), z0={tl.CharacteristicImpedance}, td={tl.Delay}, frequency={tl.Frequency}, nl={tl.NormalizedLength})",

            LossyTransmissionLineComponent ltl =>
                $"{varName} = circuit.add_lossy_transmission_line(\"{comp.Name}\", position=({x}, {y}), length={ltl.Length}, r={ltl.ResistancePerMeter}, l={ltl.InductancePerMeter}, c={ltl.CapacitancePerMeter}, g={ltl.ConductancePerMeter})",

            CoaxialCableComponent coax =>
                $"{varName} = circuit.add_coaxial_cable(\"{comp.Name}\", position=({x}, {y}), z0={coax.CharacteristicImpedance}, length={coax.Length}, vf={coax.VelocityFactor}, attenuation={coax.Attenuation})",

            MicrostripLineComponent ustrip =>
                $"{varName} = circuit.add_microstrip_line(\"{comp.Name}\", position=({x}, {y}), w={ustrip.TraceWidth}, h={ustrip.SubstrateHeight}, er={ustrip.DielectricConstant}, length={ustrip.Length})",

            // ── Power Systems, Machines, Loads & Storage ──────────────────
            SinglePhaseTransmissionLineComponent line1 =>
                $"{varName} = circuit.add_single_phase_transmission_line(\"{comp.Name}\", position=({x}, {y}), rated_voltage={line1.RatedVoltage}, frequency={line1.Frequency}, length_km={line1.LengthKm}, resistance_per_km={line1.ResistancePerKm}, inductance_per_km={line1.InductancePerKm}, capacitance_per_km={line1.CapacitancePerKm}, conductance_per_km={line1.ConductancePerKm}, model_type=\"{line1.ModelType}\")",

            TwoPhaseTransmissionLineComponent line2 =>
                $"{varName} = circuit.add_two_phase_transmission_line(\"{comp.Name}\", position=({x}, {y}), rated_voltage={line2.RatedLineVoltage}, frequency={line2.Frequency}, length_km={line2.LengthKm}, phase_displacement={line2.PhaseDisplacementDegrees}, configuration=\"{line2.ConductorConfiguration}\")",

            ThreePhaseTransmissionLineComponent line3 =>
