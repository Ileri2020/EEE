                    sb.Append($", am_amplitude={i.AmAmplitude}, am_offset={i.AmOffset}, am_mod_freq={i.AmModulationFrequency}, am_carrier_freq={i.AmCarrierFrequency}, am_delay={i.AmDelay}");
