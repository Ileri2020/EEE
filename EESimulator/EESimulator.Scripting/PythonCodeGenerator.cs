        }
        sb.Append(")");
        return sb.ToString();
    }

    /// <summary>
    /// Converts a component name to a valid Python identifier
    /// (lowercased, non-alphanumeric chars replaced with underscores).
    /// </summary>
    public static string SanitizePythonName(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "comp";

        var sb = new StringBuilder();
        foreach (char c in name.ToLowerInvariant())
        {
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');
        }

        // Ensure it doesn't start with a digit
        if (sb.Length > 0 && char.IsDigit(sb[0]))
            sb.Insert(0, 'c');

        return sb.ToString();
    }

    public static string CommandToStatement(ICommand command)
    {
        return command.ToPythonScript();
    }
}
