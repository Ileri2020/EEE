using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using EESimulator.Core.Models;

namespace EESimulator.Formats;

/// <summary>
/// Exports and imports SPICE netlists (.cir / .sp), standard for simulation interchange
/// with SpiceSharp, LTspice, Ngspice, and PSpice.
/// </summary>
public class SpiceNetlistExporter
{
    public static string ExportToSpice(CircuitNode circuit, EESimulator.Engine.Simulation.SimulationSettings? settings = null)
    {
        var sb = new StringBuilder();
        var inv = CultureInfo.InvariantCulture;

        sb.AppendLine($"* SPICE Netlist generated by EESimulator: {circuit.Title}");
        sb.AppendLine();

        // Build net mappings from connections
        // Map (ComponentId, PinId) -> NodeName
        var pinNodeMap = new Dictionary<(Guid, string), string>();
        int netCounter = 1;

        foreach (var conn in circuit.Connections)
        {
            var key1 = (conn.FromComponentId, conn.FromPin);
            var key2 = (conn.ToComponentId, conn.ToPin);

            string nodeName;
            if (pinNodeMap.TryGetValue(key1, out var existing1))
            {
                nodeName = existing1;
            }
            else if (pinNodeMap.TryGetValue(key2, out var existing2))
            {
                nodeName = existing2;
            }
            else
            {
                nodeName = string.IsNullOrWhiteSpace(conn.NetName) ? $"N{netCounter++}" : conn.NetName;
            }

            pinNodeMap[key1] = nodeName;
            pinNodeMap[key2] = nodeName;
        }

        // Helper to get connected node or ground
        string GetNode(ComponentNode comp, string pin)
        {
            if (comp is GroundNode) return "0";
            if (pinNodeMap.TryGetValue((comp.Id, pin), out var n)) return n;
            var pObj = comp.GetPin(pin);
            if (pObj != null && pinNodeMap.TryGetValue((comp.Id, pObj.Id), out var n2)) return n2;
            return "0";
        }

        string GetPinOrFirst(ComponentNode comp, int index, string fallbackPin)
        {
            if (comp.Pins.Count > index) return GetNode(comp, comp.Pins[index].Id);
            return GetNode(comp, fallbackPin);
        }

        void AppendLineSection(string name, string from, string to, double resistance, double inductance,
            double capacitance, double conductance, bool includeShunt)
        {
            string seriesNode = $"N_{name}_SER";
            sb.AppendLine($"R_{name} {from} {seriesNode} {Math.Max(resistance, 1e-6).ToString(inv)}");
            if (inductance > 0)
                sb.AppendLine($"L_{name} {seriesNode} {to} {inductance.ToString(inv)}");
            else
                sb.AppendLine($"R_{name}_LINK {seriesNode} {to} 1e-6");

            if (!includeShunt) return;
            if (capacitance > 0)
            {
                sb.AppendLine($"C_{name}_FROM {from} 0 {(capacitance / 2).ToString(inv)}");
                sb.AppendLine($"C_{name}_TO {to} 0 {(capacitance / 2).ToString(inv)}");
            }
            if (conductance > 0)
            {
                double halfShuntResistance = 2 / conductance;
                sb.AppendLine($"R_{name}_G_FROM {from} 0 {halfShuntResistance.ToString(inv)}");
                sb.AppendLine($"R_{name}_G_TO {to} 0 {halfShuntResistance.ToString(inv)}");
            }
        }

        void AppendFixedSineSource(string name, string positive, string negative, double voltageRms,
            double frequency, double phaseDegrees)
        {
            double peak = Math.Max(voltageRms, 0) * Math.Sqrt(2);
            sb.AppendLine($"V_{name} {positive} {negative} SIN(0 {peak.ToString(inv)} {Math.Max(frequency, 0.01).ToString(inv)} 0 0 {phaseDegrees.ToString(inv)}) AC {voltageRms.ToString(inv)} {phaseDegrees.ToString(inv)}");
        }

        var models = new List<string>();

        // Write SPICE component lines
        foreach (var comp in circuit.Components)
        {
            switch (comp)
            {
                case EESimulator.Core.Components.Electrical.ResistorComponent r:
                    sb.AppendLine($"R_{r.Name} {GetPinOrFirst(r, 0, "pin1")} {GetPinOrFirst(r, 1, "pin2")} {r.Resistance.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.CapacitorComponent c:
                    string icStr = c.InitialCondition != 0 ? $" IC={c.InitialCondition.ToString(inv)}" : "";
                    sb.AppendLine($"C_{c.Name} {GetPinOrFirst(c, 0, "pin1")} {GetPinOrFirst(c, 1, "pin2")} {c.Capacitance.ToString(inv)}{icStr}");
                    break;
                case EESimulator.Core.Components.Electrical.InductorComponent l:
                    string icL = l.InitialCondition != 0 ? $" IC={l.InitialCondition.ToString(inv)}" : "";
                    sb.AppendLine($"L_{l.Name} {GetPinOrFirst(l, 0, "pin1")} {GetPinOrFirst(l, 1, "pin2")} {l.Inductance.ToString(inv)}{icL}");
                    break;
                case EESimulator.Core.Components.Electrical.VoltageSourceComponent v:
                    sb.AppendLine($"V_{v.Name} {GetPinOrFirst(v, 0, "positive")} {GetPinOrFirst(v, 1, "negative")} DC {v.Voltage.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.CurrentSourceComponent i:
                    sb.AppendLine($"I_{i.Name} {GetPinOrFirst(i, 0, "positive")} {GetPinOrFirst(i, 1, "negative")} DC {i.Current.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.SinglePhaseTransmissionLineComponent line1:
                    string singleFrom = GetPinOrFirst(line1, 0, "from");
                    string singleTo = GetPinOrFirst(line1, 1, "to");
                    string singleLineInput = singleFrom;
                    if (line1.SupplyMode == "FixedVoltageSource")
                    {
                        singleLineInput = $"N_{line1.Name}_SOURCE";
                        AppendFixedSineSource($"{line1.Name}_SOURCE", singleFrom, singleLineInput,
                            line1.FixedVoltageRms, line1.Frequency, line1.InitialPhaseAngle);
                    }
                    AppendLineSection($"{line1.Name}_LINE", singleLineInput, singleTo,
                        line1.TotalResistance, line1.InductancePerKm * line1.LengthKm,
                        line1.CapacitancePerKm * line1.LengthKm, line1.ConductancePerKm * line1.LengthKm,
                        line1.ModelType != "Short Line");
                    break;
                case EESimulator.Core.Components.Electrical.TwoPhaseTransmissionLineComponent line2:
                    for (int phase = 0; phase < 2; phase++)
                    {
                        string phaseFrom = GetPinOrFirst(line2, phase * 2, phase == 0 ? "a_from" : "b_from");
                        string phaseTo = GetPinOrFirst(line2, phase * 2 + 1, phase == 0 ? "a_to" : "b_to");
                        string phaseLineInput = phaseFrom;
                        if (line2.SupplyMode == "FixedVoltageSource")
                        {
                            phaseLineInput = $"N_{line2.Name}_PH{phase + 1}_SOURCE";
                            double phaseDegrees = phase == 0 ? 0 :
                                line2.ConductorConfiguration == "SplitPhaseThreeWire" ? 180 : line2.PhaseDisplacementDegrees;
                            AppendFixedSineSource($"{line2.Name}_PH{phase + 1}_SOURCE", phaseFrom, phaseLineInput,
                                line2.FixedVoltageRms, line2.Frequency, phaseDegrees);
                        }
                        AppendLineSection($"{line2.Name}_PH{phase + 1}", phaseLineInput, phaseTo,
                            line2.ResistancePerKm * line2.LengthKm, line2.InductancePerKm * line2.LengthKm,
                            line2.CapacitancePerKm * line2.LengthKm, line2.ConductancePerKm * line2.LengthKm, true);
                    }
                    if (line2.ConductorConfiguration == "SplitPhaseThreeWire")
                    {
                        AppendLineSection($"{line2.Name}_NEUTRAL", GetPinOrFirst(line2, 4, "neutral_from"),
                            GetPinOrFirst(line2, 5, "neutral_to"), line2.ResistancePerKm * line2.LengthKm,
                            line2.InductancePerKm * line2.LengthKm, line2.CapacitancePerKm * line2.LengthKm,
                            line2.ConductancePerKm * line2.LengthKm, true);
                    }
                    break;
                case EESimulator.Core.Components.Electrical.ThreePhaseTransmissionLineComponent line3:
                    for (int phase = 0; phase < 3; phase++)
                    {
                        string phaseFrom = GetPinOrFirst(line3, phase, $"{(char)('A' + phase)}_send");
                        string phaseTo = GetPinOrFirst(line3, phase + 3, $"{(char)('A' + phase)}_receive");
                        string phaseLineInput = phaseFrom;
                        if (line3.SupplyMode == "FixedVoltageSource")
                        {
                            phaseLineInput = $"N_{line3.Name}_PH{phase + 1}_SOURCE";
                            double phaseOrder = line3.PhaseSequence == "ACB" ? -1 : 1;
                            AppendFixedSineSource($"{line3.Name}_PH{phase + 1}_SOURCE", phaseFrom, phaseLineInput,
                                line3.FixedPhaseVoltageRms, line3.Frequency, phaseOrder * phase * 120);
                        }
                        AppendLineSection($"{line3.Name}_PH{phase + 1}", phaseLineInput, phaseTo,
                            line3.ResistancePerKmPerPhase * line3.LengthKm,
                            line3.InductancePerKmPerPhase * line3.LengthKm,
                            line3.CapacitancePerKmPerPhase * line3.LengthKm,
                            line3.ConductancePerKmPerPhase * line3.LengthKm,
                            line3.ModelType != "Short");
                    }
                    if (line3.Connection == "Four-wire")
                    {
                        AppendLineSection($"{line3.Name}_NEUTRAL", GetPinOrFirst(line3, 6, "N_send"),
                            GetPinOrFirst(line3, 7, "N_receive"), line3.NeutralImpedance, 0, 0, 0, false);
                    }
                    break;
                case EESimulator.Core.Components.Electrical.DiodeComponent d:
                    string dModel = $"D_{d.Name}_mod";
                    sb.AppendLine($"D_{d.Name} {GetPinOrFirst(d, 0, "anode")} {GetPinOrFirst(d, 1, "cathode")} {dModel}");
                    models.Add($".model {dModel} D (IS={d.SaturationCurrent.ToString(inv)} N={d.EmissionCoefficient.ToString(inv)} BV={d.BreakdownVoltage.ToString(inv)} RS={d.SeriesResistance.ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electronics.BJTComponent b:
                    string bModel = $"Q_{b.Name}_mod";
                    sb.AppendLine($"Q_{b.Name} {GetNode(b, "collector")} {GetNode(b, "base")} {GetNode(b, "emitter")} {bModel}");
                    models.Add($".model {bModel} {(b.Polarity == EESimulator.Core.Components.Electronics.BjtPolarity.NPN ? "NPN" : "PNP")} (BF={b.GainBeta.ToString(inv)} IS={b.SaturationCurrent.ToString(inv)} VAF={b.EarlyVoltage.ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electronics.MOSFETComponent m:
                    string mModel = $"M_{m.Name}_mod";
                    sb.AppendLine($"M_{m.Name} {GetNode(m, "drain")} {GetNode(m, "gate")} {GetNode(m, "source")} {GetNode(m, "source")} {mModel} W={m.ChannelWidth.ToString(inv)} L={m.ChannelLength.ToString(inv)}");
                    models.Add($".model {mModel} {(m.Channel == EESimulator.Core.Components.Electronics.MosfetChannel.NChannel ? "NMOS" : "PMOS")} (VTO={m.ThresholdVoltage.ToString(inv)} KP={m.Transconductance.ToString(inv)} LAMBDA={m.Lambda.ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electronics.JFETComponent j:
                    string jModel = $"J_{j.Name}_mod";
                    sb.AppendLine($"J_{j.Name} {GetNode(j, "drain")} {GetNode(j, "gate")} {GetNode(j, "source")} {jModel}");
                    models.Add($".model {jModel} {(j.Channel == EESimulator.Core.Components.Electronics.JfetChannel.NChannel ? "NJF" : "PJF")} (VTO={j.ThresholdVoltage.ToString(inv)} BETA={j.Transconductance.ToString(inv)} LAMBDA={j.Lambda.ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electrical.VCVSComponent vcvs:
                    sb.AppendLine($"E_{vcvs.Name} {GetPinOrFirst(vcvs, 0, "out_pos")} {GetPinOrFirst(vcvs, 1, "out_neg")} {GetPinOrFirst(vcvs, 2, "ctrl_pos")} {GetPinOrFirst(vcvs, 3, "ctrl_neg")} {vcvs.VoltageGain.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.VCCSComponent vccs:
                    sb.AppendLine($"G_{vccs.Name} {GetPinOrFirst(vccs, 0, "out_pos")} {GetPinOrFirst(vccs, 1, "out_neg")} {GetPinOrFirst(vccs, 2, "ctrl_pos")} {GetPinOrFirst(vccs, 3, "ctrl_neg")} {vccs.Transconductance.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.CCVSComponent ccvs:
                    string hSense = string.IsNullOrEmpty(ccvs.ControllingSource) ? $"V_sense_{ccvs.Name}" : ccvs.ControllingSource;
                    sb.AppendLine($"H_{ccvs.Name} {GetPinOrFirst(ccvs, 0, "out_pos")} {GetPinOrFirst(ccvs, 1, "out_neg")} {hSense} {ccvs.Transresistance.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.CCCSComponent cccs:
                    string fSense = string.IsNullOrEmpty(cccs.ControllingSource) ? $"V_sense_{cccs.Name}" : cccs.ControllingSource;
                    sb.AppendLine($"F_{cccs.Name} {GetPinOrFirst(cccs, 0, "out_pos")} {GetPinOrFirst(cccs, 1, "out_neg")} {fSense} {cccs.CurrentGain.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.VoltageSwitchComponent vsw:
                    string swMod = $"S_{vsw.Name}_mod";
                    sb.AppendLine($"S_{vsw.Name} {GetPinOrFirst(vsw, 0, "sw_pos")} {GetPinOrFirst(vsw, 1, "sw_neg")} {GetPinOrFirst(vsw, 2, "ctrl_pos")} {GetPinOrFirst(vsw, 3, "ctrl_neg")} {swMod}");
                    models.Add($".model {swMod} VSWITCH (RON={vsw.ResistanceOn.ToString(inv)} ROFF={vsw.ResistanceOff.ToString(inv)} VON={vsw.Threshold.ToString(inv)} VOFF={(vsw.Threshold - vsw.Hysteresis).ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electrical.CurrentSwitchComponent csw:
                    string cswMod = $"W_{csw.Name}_mod";
                    string wSense = string.IsNullOrEmpty(csw.ControllingSource) ? $"V_sense_{csw.Name}" : csw.ControllingSource;
                    sb.AppendLine($"W_{csw.Name} {GetPinOrFirst(csw, 0, "sw_pos")} {GetPinOrFirst(csw, 1, "sw_neg")} {wSense} {cswMod}");
                    models.Add($".model {cswMod} ISWITCH (RON={csw.ResistanceOn.ToString(inv)} ROFF={csw.ResistanceOff.ToString(inv)} ION={csw.Threshold.ToString(inv)} IOFF={(csw.Threshold - csw.Hysteresis).ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electrical.RelayComponent relay:
                    string relayMod = $"S_{relay.Name}_contact_mod";
                    sb.AppendLine($"R_{relay.Name}_coil {GetNode(relay, "coil_positive")} {GetNode(relay, "coil_negative")} {relay.CoilResistance.ToString(inv)}");
                    sb.AppendLine($"S_{relay.Name} {GetNode(relay, "common")} {GetNode(relay, "normally_open")} {GetNode(relay, "coil_positive")} {GetNode(relay, "coil_negative")} {relayMod}");
                    models.Add($".model {relayMod} VSWITCH (RON={relay.ContactResistance.ToString(inv)} ROFF={relay.OpenResistance.ToString(inv)} VON={relay.PullInVoltage.ToString(inv)} VOFF={relay.DropoutVoltage.ToString(inv)})");
                    break;
                case EESimulator.Core.Components.Electronics.OpAmpComponent op:
                    sb.AppendLine($"E_{op.Name} {GetNode(op, "out")} 0 {GetNode(op, "in_pos")} {GetNode(op, "in_neg")} {op.OpenLoopGain.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.MutualInductanceComponent k:
                    sb.AppendLine($"K_{k.Name} {k.Inductor1} {k.Inductor2} {k.Coupling.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.TransmissionLineComponent tline:
                    sb.AppendLine($"T_{tline.Name} {GetPinOrFirst(tline, 0, "pos1")} {GetPinOrFirst(tline, 1, "neg1")} {GetPinOrFirst(tline, 2, "pos2")} {GetPinOrFirst(tline, 3, "neg2")} Z0={tline.CharacteristicImpedance.ToString(inv)} TD={tline.Delay.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.Electrical.VoltageDelayComponent vdelay:
                    sb.AppendLine($"U_{vdelay.Name} {GetPinOrFirst(vdelay, 0, "out_pos")} {GetPinOrFirst(vdelay, 1, "out_neg")} {GetPinOrFirst(vdelay, 2, "in_pos")} {GetPinOrFirst(vdelay, 3, "in_neg")} VoltageDelay TD={vdelay.Delay.ToString(inv)}");
                    break;
                case EESimulator.Core.Components.General.WireComponent w when w.Resistance > 0:
                    sb.AppendLine($"R_wire_{w.Name} {GetPinOrFirst(w, 0, "start")} {GetPinOrFirst(w, 1, "end")} {w.Resistance.ToString(inv)}");
                    break;
            }
        }

        // Include SPICE models
        if (models.Count > 0)
        {
            sb.AppendLine();
            foreach (var mod in models)
            {
                sb.AppendLine(mod);
            }
        }

        sb.AppendLine();
        if (settings != null)
        {
            switch (settings.Analysis)
            {
                case EESimulator.Engine.Simulation.AnalysisType.Transient:
                    sb.AppendLine($".tran {settings.StepTime.ToString(inv)} {settings.StopTime.ToString(inv)} {settings.StartTime.ToString(inv)}");
                    break;
                case EESimulator.Engine.Simulation.AnalysisType.AC:
                    sb.AppendLine($".ac dec {settings.AcPoints} {settings.AcStartFrequency.ToString(inv)} {settings.AcStopFrequency.ToString(inv)}");
                    break;
                case EESimulator.Engine.Simulation.AnalysisType.DCSweep:
                    sb.AppendLine($".dc {settings.DcSweepSource} {settings.DcStart.ToString(inv)} {settings.DcStop.ToString(inv)} {settings.DcStep.ToString(inv)}");
                    break;
                default:
                    sb.AppendLine(".op");
                    break;
            }
        }
        else
        {
            sb.AppendLine(".op");
        }

        sb.AppendLine(".end");
        return sb.ToString();
    }

    public static void SaveToFile(CircuitNode circuit, string filePath)
    {
        string netlist = ExportToSpice(circuit);
        File.WriteAllText(filePath, netlist);
    }
}
